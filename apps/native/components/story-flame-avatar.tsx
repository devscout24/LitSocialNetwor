export function resolveStoryFlameStage(
  ageHours = 0,
  explicitStage?: StoryFlameStage,
): StoryFlameStage {
  if (explicitStage) return explicitStage;
  if (ageHours <= 3) return "full";
  if (ageHours <= 11) return "medium";
  if (ageHours < 20) return "small";
  return "none";
}

export function StoryFlameAvatar({
  avatar,
  ageHours = 0,
  stage: explicitStage,
}: StoryFlameAvatarProps) {
  const uid = useId().replace(/[^a-zA-Z0-9]/g, "");
  const resolvedStage = resolveStoryFlameStage(ageHours, explicitStage);

  const [frameIdx, setFrameIdx] = useState(0);
  const pulseAnim = useRef(new Animated.Value(0)).current;

  const timingConfig = useMemo(() => {
    switch (resolvedStage) {
      case "full":
        return {
          frameMs: 95,
          pulseMs: 260,
        };
      case "medium":
        return {
          frameMs: 210,
          pulseMs: 560,
        };
      case "small":
        return {
          frameMs: 360,
          pulseMs: 1050,
        };
      case "none":
      default:
        return null;
    }
  }, [resolvedStage]);

  useEffect(() => {
    if (!timingConfig) {
      pulseAnim.setValue(0);
      return;
    }

    const interval = setInterval(() => {
      setFrameIdx((prev) => (prev + 1) % 6);
    }, timingConfig.frameMs);

    const pulseLoop = Animated.loop(
      Animated.sequence([
        Animated.timing(pulseAnim, {
          toValue: 1,
          duration: timingConfig.pulseMs,
          easing: Easing.inOut(Easing.sin),
          useNativeDriver: true,
        }),
        Animated.timing(pulseAnim, {
          toValue: 0,
          duration: timingConfig.pulseMs,
          easing: Easing.inOut(Easing.sin),
          useNativeDriver: true,
        }),
      ]),
    );

    pulseLoop.start();

    return () => {
      clearInterval(interval);
      pulseLoop.stop();
    };
  }, [timingConfig, pulseAnim]);

  const activePath = useMemo(() => {
    if (resolvedStage === "full") {
      return FIGMA_FULL_FRAMES[frameIdx % FIGMA_FULL_FRAMES.length];
    }
    if (resolvedStage === "medium") {
      return FIGMA_MEDIUM_FRAMES[frameIdx % FIGMA_MEDIUM_FRAMES.length];
    }
    if (resolvedStage === "small") {
      return FIGMA_SMALL_FRAMES[frameIdx % FIGMA_SMALL_FRAMES.length];
    }
    return null;
  }, [resolvedStage, frameIdx]);

  const innerCorePath = useMemo(() => {
    if (resolvedStage === "full") {
      return FIGMA_MEDIUM_FRAMES[(frameIdx + 2) % FIGMA_MEDIUM_FRAMES.length];
    }
    if (resolvedStage === "medium") {
      return FIGMA_SMALL_FRAMES[(frameIdx + 2) % FIGMA_SMALL_FRAMES.length];
    }
    return null;
  }, [resolvedStage, frameIdx]);

  const activeWisps = useMemo(() => {
    if (resolvedStage === "full") {
      return FULL_WISPS[frameIdx % FULL_WISPS.length];
    }
    if (resolvedStage === "medium") {
      return MEDIUM_WISPS[frameIdx % MEDIUM_WISPS.length];
    }
    return null;
  }, [resolvedStage, frameIdx]);

  const gradId = `figmaFlameGrad_${uid}`;
  const coreGradId = `figmaFlameCore_${uid}`;

  return (
    <View style={styles.flameRingBox}>
      {resolvedStage === "none" ? (
        <Svg
          width={51.974}
          height={58.7955}
          viewBox="0 0 51.974 58.7955"
          style={styles.svgLayer}
        >
          <Circle
            cx="24.97"
            cy="39.01"
            r="21.1"
            fill="none"
            stroke="rgba(255,255,255,0.22)"
            strokeWidth="1.2"
          />
        </Svg>
      ) : (
        <Animated.View
          style={[
            styles.svgLayer,
            {
              opacity: pulseAnim.interpolate({
                inputRange: [0, 1],
                outputRange: [0.94, 1],
              }),
            },
          ]}
        >
          <Svg
            width={51.974}
            height={58.7955}
            viewBox="0 0 51.974 58.7955"
            style={{ overflow: "visible" }}
          >
            <Defs>
              {/* Exact Figma linearGradient from story_flame_ring (283:879) */}
              <LinearGradient
                id={gradId}
                x1="14.812"
                y1="56.1917"
                x2="36.8154"
                y2="4.76592"
                gradientUnits="userSpaceOnUse"
              >
                <Stop offset="0%" stopColor="#F09B1E" />
                <Stop offset="100%" stopColor="#ED4113" />
              </LinearGradient>
              {/* Inner golden-yellow hot core highlight */}
              <LinearGradient
                id={coreGradId}
                x1="16"
                y1="54"
                x2="35"
                y2="10"
                gradientUnits="userSpaceOnUse"
              >
                <Stop offset="0%" stopColor="#FFE042" stopOpacity="0.75" />
                <Stop offset="55%" stopColor="#F09B1E" stopOpacity="0.45" />
                <Stop offset="100%" stopColor="#ED4113" stopOpacity="0" />
              </LinearGradient>
            </Defs>

            <G>
              {/* Detached rising flame wisps */}
              {activeWisps?.top ? (
                <Path d={activeWisps.top} fill="#ED4113" />
              ) : null}
              {activeWisps?.side ? (
                <Path d={activeWisps.side} fill="#ED4113" opacity={0.85} />
              ) : null}

              {/* Primary Figma Flame Crescent Ring */}
              {activePath && (
                <Path
                  d={activePath}
                  fill={`url(#${gradId})`}
                  fillRule="evenodd"
                  clipRule="evenodd"
                />
              )}

              {/* Inner shimmering golden core */}
              {innerCorePath && (
                <Path
                  d={innerCorePath}
                  fill={`url(#${coreGradId})`}
                  fillRule="evenodd"
                  clipRule="evenodd"
                />
              )}
            </G>
          </Svg>
        </Animated.View>
      )}

      {/* Exact Figma Story Avatar placement (283:881) */}
      <Image source={avatar} style={styles.flameStoryAvatar} />
    </View>
  );
}

